import { useState } from 'react'
import {
  getAdminGovernanceOptions,
  getAdminGovernanceSummary,
  getAdminNotifications,
  type AdminNotification,
} from '../../services/adminDashboardService'
import {
  adminMarkNotificationRead,
  getNotificationDetails,
  getNotificationRecipients,
  type NotificationDetail,
  type NotificationRecipientsResult,
} from '../../services/notificationCenterService'
import { useAdminResource } from '../../hooks/useAdminResource'
import {
  AdminPage,
  Badge,
  Button,
  EmptyState,
  ErrorPanel,
  Field,
  FilterBar,
  LoadingPanel,
  Modal,
  Pagination,
  Panel,
  Select,
  StatCard,
  StatusBadge,
  Table,
  Td,
  Th,
  TextInput,
  dateTime,
  humanise,
  num,
} from '../../components/admin/AdminUi'

/**
 * Admin notification centre (institution-wide).
 *
 * Reads the real database rows through GET /admin/notifications and adds the
 * detail actions backed by /admin/notifications-centre/*: View Details,
 * View Recipients (per-recipient read state — reading is strictly per
 * recipient) and Mark as Read, which records the read transition on delivery
 * telemetry. There is deliberately no admin delete/archive: removing rows
 * would destroy per-recipient delivery history, so only state changes are
 * offered on this surface.
 */
export default function AdminNotificationsPage() {
  const [type, setType] = useState('')
  const [priority, setPriority] = useState('')
  const [readState, setReadState] = useState('')
  const [departmentId, setDepartmentId] = useState('')
  const [recipient, setRecipient] = useState('')
  const [search, setSearch] = useState('')
  const [fromDate, setFromDate] = useState('')
  const [toDate, setToDate] = useState('')
  const [page, setPage] = useState(1)

  // Detail / recipients modals
  const [detail, setDetail] = useState<NotificationDetail | null>(null)
  const [detailLoading, setDetailLoading] = useState(false)
  const [recipients, setRecipients] = useState<NotificationRecipientsResult | null>(null)
  const [recipientsLoading, setRecipientsLoading] = useState(false)
  const [busy, setBusy] = useState(false)
  const [actionError, setActionError] = useState('')

  const options = useAdminResource(() => getAdminGovernanceOptions())
  const overview = useAdminResource(() => getAdminGovernanceSummary())
  const resource = useAdminResource(
    () =>
      getAdminNotifications({
        type,
        priority,
        read: readState,
        department_id: departmentId,
        recipient,
        search,
        from_date: fromDate,
        to_date: toDate,
        page,
        per_page: 15,
      }),
    [type, priority, readState, departmentId, recipient, search, fromDate, toDate, page],
  )

  const data = resource.data
  const summary = overview.data?.notifications

  const apply = (setter: (value: string) => void) => (value: string) => {
    setter(value)
    setPage(1)
  }

  const openDetails = async (notification: AdminNotification) => {
    setRecipients(null)
    setDetail(null)
    setActionError('')
    setDetailLoading(true)
    try {
      const result = await getNotificationDetails(notification.id)
      setDetail(result)
    } catch {
      setActionError('Unable to load notification details.')
    } finally {
      setDetailLoading(false)
    }
  }

  const openRecipients = async (notification: AdminNotification) => {
    setDetail(null)
    setRecipients(null)
    setActionError('')
    setRecipientsLoading(true)
    try {
      const result = await getNotificationRecipients(notification.id)
      setRecipients(result)
    } catch {
      setActionError('Unable to load notification recipients.')
    } finally {
      setRecipientsLoading(false)
    }
  }

  const closeModals = () => {
    setDetail(null)
    setRecipients(null)
    setActionError('')
  }

  const markRead = async (notification: AdminNotification) => {
    setBusy(true)
    setActionError('')
    try {
      await adminMarkNotificationRead(notification.id)
      resource.reload()
    } catch {
      setActionError('Unable to mark this notification as read.')
    } finally {
      setBusy(false)
    }
  }

  return (
    <AdminPage
      title="Notifications"
      subtitle="Institution-wide alerts generated by the platform. Delivery is in-app; read state is tracked per recipient."
    >
      {/* Filters — all combinable, updating the list live */}
      <FilterBar>
        <Field label="Search" className="flex-1 min-w-[170px]">
          <TextInput
            value={search}
            onChange={apply(setSearch)}
            placeholder="Search title and message…"
          />
        </Field>
        <Field label="Recipient" className="min-w-[170px]">
          <TextInput
            value={recipient}
            onChange={apply(setRecipient)}
            placeholder="Employee name or email…"
          />
        </Field>
        <Field label="Type">
          <Select
            value={type}
            onChange={apply(setType)}
            options={options.data?.notification_types ?? []}
            placeholder="All types"
          />
        </Field>
        <Field label="Priority">
          <Select
            value={priority}
            onChange={apply(setPriority)}
            options={[
              { value: 'low', label: 'Low' },
              { value: 'normal', label: 'Normal' },
              { value: 'high', label: 'High' },
              { value: 'urgent', label: 'Urgent' },
            ]}
            placeholder="All priorities"
          />
        </Field>
        <Field label="Read state">
          <Select
            value={readState}
            onChange={apply(setReadState)}
            options={[
              { value: 'read', label: 'Read' },
              { value: 'unread', label: 'Unread' },
            ]}
            placeholder="All"
          />
        </Field>
        <Field label="Department">
          <Select
            value={departmentId}
            onChange={apply(setDepartmentId)}
            options={options.data?.departments ?? []}
            placeholder="All departments"
          />
        </Field>
        <Field label="From">
          <input
            type="date"
            className="text-sm rounded-lg border border-slate-300 bg-white px-3 py-2 text-slate-800 focus:outline-none focus:ring-2 focus:ring-jpc-500"
            value={fromDate}
            onChange={(e) => apply(setFromDate)(String(e.target.value))}
          />
        </Field>
        <Field label="To">
          <input
            type="date"
            className="text-sm rounded-lg border border-slate-300 bg-white px-3 py-2 text-slate-800 focus:outline-none focus:ring-2 focus:ring-jpc-500"
            value={toDate}
            onChange={(e) => apply(setToDate)(String(e.target.value))}
          />
        </Field>
        <Button
          variant="secondary"
          onClick={() => {
            setType(''); setPriority(''); setReadState(''); setDepartmentId('')
            setRecipient(''); setSearch(''); setFromDate(''); setToDate(''); setPage(1)
          }}
        >
          Clear
        </Button>
      </FilterBar>

      {resource.loading || options.loading || overview.loading ? (
        <LoadingPanel label="Loading notifications" />
      ) : resource.error || !data ? (
        <ErrorPanel message={resource.error ?? 'Unable to load notifications.'} onRetry={resource.reload} />
      ) : (
        <div className="space-y-6">
          {/* KPI cards — all counts from live database queries */}
          <div className="grid grid-cols-2 lg:grid-cols-5 gap-4">
            <StatCard label="Notifications" value={num(summary?.total ?? 0)} />
            <StatCard
              label="Unread"
              value={num(summary?.unread ?? 0)}
              tone={(summary?.unread ?? 0) > 0 ? 'warn' : 'ok'}
            />
            <StatCard
              label="High priority"
              value={num(summary?.high_priority ?? 0)}
              tone={(summary?.high_priority ?? 0) > 0 ? 'danger' : 'ok'}
            />
            <StatCard label="Sent last 24 h" value={num(summary?.last_24h ?? 0)} tone="info" />
            <StatCard
              label="Failed deliveries"
              value={num(summary?.failed_deliveries ?? 0)}
              tone={(summary?.failed_deliveries ?? 0) > 0 ? 'danger' : 'ok'}
              hint="From delivery telemetry"
            />
          </div>

          {actionError && (
            <p role="alert" className="text-sm text-red-700 bg-red-50 border border-red-200 rounded-xl px-3 py-2">
              {actionError}
            </p>
          )}

          <Panel
            title="Notification log"
            description={`${data.meta.total} records · newest first · delivery channel: in-app`}
          >
            {data.items.length === 0 ? (
              <EmptyState title="No notifications match these filters" message="Try clearing a filter to widen the search." />
            ) : (
              <>
                {/* Desktop: the full log table. Text wraps instead of locking
                    column widths, so the table fits the panel width without
                    horizontal scrolling on normal desktop screens. */}
                <div className="hidden xl:block">
                  <Table>
                    <thead>
                      <tr>
                        <Th>Notification</Th>
                        <Th>Type</Th>
                        <Th>Priority</Th>
                        <Th>Recipient</Th>
                        <Th>Department</Th>
                        <Th>Triggered by</Th>
                        <Th>Delivery</Th>
                        <Th>Read</Th>
                        <Th>Date &amp; time</Th>
                        <Th>Actions</Th>
                      </tr>
                    </thead>
                    <tbody>
                      {data.items.map((notification) => (
                        <tr key={notification.id} className="border-b border-slate-100 last:border-0 hover:bg-slate-50 align-top">
                          <Td>
                            <p className="font-semibold text-slate-800 break-words">{notification.title}</p>
                            <p className="text-[11px] text-slate-500 line-clamp-2 break-words">{notification.message}</p>
                          </Td>
                          <Td><span className="block break-words whitespace-normal">{humanise(notification.type)}</span></Td>
                          <Td>
                            <Badge
                              tone={
                                ['high', 'urgent', 'critical'].includes(notification.priority)
                                  ? 'danger'
                                  : notification.priority === 'medium'
                                    ? 'warn'
                                    : 'neutral'
                              }
                            >
                              {humanise(notification.priority)}
                            </Badge>
                          </Td>
                          <Td>
                            <p className="text-slate-700 text-xs break-words">{notification.recipient}</p>
                            <p className="text-[11px] text-slate-400 break-words">{notification.recipient_email}</p>
                          </Td>
                          <Td className="text-xs text-slate-600 break-words whitespace-normal">{notification.department ?? '—'}</Td>
                          <Td className="text-xs text-slate-600 break-words whitespace-normal">{notification.triggered_by ?? '—'}</Td>
                          <Td>
                            <StatusBadge status={notification.delivery_status ?? 'sent'} />
                            <p className="text-[10px] text-slate-400 mt-0.5">In-App</p>
                          </Td>
                          <Td>
                            {notification.is_read ? (
                              <div>
                                <Badge tone="ok">Read</Badge>
                                <p className="text-[10px] text-slate-400 mt-0.5">{dateTime(notification.read_at)}</p>
                              </div>
                            ) : (
                              <Badge tone="warn">Unread</Badge>
                            )}
                          </Td>
                          <Td className="text-slate-500 text-xs">{dateTime(notification.created_at)}</Td>
                          <Td>
                            <div className="flex flex-col gap-1">
                              <Button variant="ghost" className="text-xs py-1 px-2" onClick={() => openDetails(notification)}>
                                Details
                              </Button>
                              <Button variant="ghost" className="text-xs py-1 px-2" onClick={() => openRecipients(notification)}>
                                Recipients
                              </Button>
                              {!notification.is_read && (
                                <Button
                                  variant="secondary"
                                  className="text-xs py-1 px-2"
                                  disabled={busy}
                                  onClick={() => markRead(notification)}
                                >
                                  Mark read
                                </Button>
                              )}
                            </div>
                          </Td>
                        </tr>
                      ))}
                    </tbody>
                  </Table>
                </div>

                {/* Tablet & mobile: a card per notification so no information is
                    lost and no horizontal scrolling is ever needed. */}
                <div className="xl:hidden space-y-3">
                  {data.items.map((notification) => (
                    <div key={notification.id} className="rounded-2xl border border-slate-200 bg-white p-4 space-y-2.5">
                      <div className="flex items-start justify-between gap-3">
                        <div className="min-w-0">
                          <p className="font-semibold text-slate-800 break-words">{notification.title}</p>
                          <p className="text-[11px] text-slate-500 line-clamp-3 break-words">{notification.message}</p>
                        </div>
                        <Badge tone={notification.is_read ? 'ok' : 'warn'}>{notification.is_read ? 'Read' : 'Unread'}</Badge>
                      </div>

                      <div className="flex flex-wrap gap-1.5">
                        <Badge tone="info">{humanise(notification.type)}</Badge>
                        <Badge
                          tone={
                            ['high', 'urgent', 'critical'].includes(notification.priority)
                              ? 'danger'
                              : notification.priority === 'medium'
                                ? 'warn'
                                : 'neutral'
                          }
                        >
                          {humanise(notification.priority)}
                        </Badge>
                        <Badge tone="neutral">{notification.delivery_status ?? 'sent'} · In-App</Badge>
                      </div>

                      <dl className="grid grid-cols-1 sm:grid-cols-2 gap-x-4 gap-y-1 text-xs">
                        <div className="flex gap-1">
                          <dt className="text-slate-400">Recipient</dt>
                          <dd className="font-medium text-slate-700 break-all">{notification.recipient}</dd>
                        </div>
                        <div className="flex gap-1">
                          <dt className="text-slate-400">Department</dt>
                          <dd className="text-slate-700 break-words">{notification.department ?? '—'}</dd>
                        </div>
                        <div className="flex gap-1">
                          <dt className="text-slate-400">Triggered by</dt>
                          <dd className="text-slate-700 break-words">{notification.triggered_by ?? '—'}</dd>
                        </div>
                        <div className="flex gap-1">
                          <dt className="text-slate-400">Received</dt>
                          <dd className="text-slate-700">{dateTime(notification.created_at)}</dd>
                        </div>
                        {notification.is_read && notification.read_at ? (
                          <div className="flex gap-1 sm:col-span-2">
                            <dt className="text-slate-400">Read at</dt>
                            <dd className="text-emerald-600">{dateTime(notification.read_at)}</dd>
                          </div>
                        ) : null}
                      </dl>

                      <div className="flex flex-wrap gap-2 pt-1">
                        <Button variant="secondary" className="text-xs py-1.5 px-3" onClick={() => openDetails(notification)}>
                          Details
                        </Button>
                        <Button variant="secondary" className="text-xs py-1.5 px-3" onClick={() => openRecipients(notification)}>
                          Recipients
                        </Button>
                        {!notification.is_read && (
                          <Button
                            variant="secondary"
                            className="text-xs py-1.5 px-3"
                            disabled={busy}
                            onClick={() => markRead(notification)}
                          >
                            Mark read
                          </Button>
                        )}
                      </div>
                    </div>
                  ))}
                </div>
                <Pagination meta={data.meta} onPageChange={setPage} />
              </>
            )}
          </Panel>
        </div>
      )}

      {/* ── View Details modal ── */}
      {detailLoading && !detail && !recipients && (
        <Modal open title="Notification Details" onClose={closeModals}>
          <LoadingPanel rows={2} />
        </Modal>
      )}
      {detail && !recipients && (
        <Modal
          open
          title="Notification Details"
          onClose={closeModals}
          footer={
            <>
              {detail.related ? <Badge tone="info">{detail.related.label}</Badge> : null}
              <Button variant="secondary" onClick={closeModals}>
                Close
              </Button>
            </>
          }
        >
          <div className="space-y-4">
            <div className="flex items-start justify-between gap-3">
              <h3 className="text-lg font-black text-slate-900">{detail.title}</h3>
              <Badge
                tone={['high', 'urgent', 'critical'].includes(detail.priority) ? 'danger' : 'neutral'}
              >
                {humanise(detail.priority)}
              </Badge>
            </div>

            <p className="text-sm text-slate-600 whitespace-pre-line">
              {detail.message ?? 'No message body.'}
            </p>

            <dl className="grid grid-cols-2 gap-x-4 gap-y-2 text-sm">
              <dt className="text-slate-400">Type</dt>
              <dd className="text-slate-700">{humanise(detail.type)}</dd>
              <dt className="text-slate-400">Triggered by</dt>
              <dd className="text-slate-700">{detail.triggered_by ?? '—'}</dd>
              <dt className="text-slate-400">Recipient count</dt>
              <dd className="text-slate-700 tabular-nums">{detail.recipient_count ?? 1}</dd>
              <dt className="text-slate-400">Delivery channel</dt>
              <dd className="text-slate-700">In-App ({detail.delivery_status ?? 'sent'})</dd>
              <dt className="text-slate-400">Read state</dt>
              <dd className="text-slate-700">{detail.is_read ? `Read · ${dateTime(detail.read_at)}` : 'Unread'}</dd>
              <dt className="text-slate-400">Recipient</dt>
              <dd className="text-slate-700">
                {detail.recipient ?? '—'}
                {detail.employee_number ? ` · #${detail.employee_number}` : ''}
                {detail.department ? ` · ${detail.department}` : ''}
              </dd>
              <dt className="text-slate-400">Created</dt>
              <dd className="text-slate-700">{dateTime(detail.created_at)}</dd>
            </dl>

            {detail.related ? (
              <div className="bg-jpc-50 border border-jpc-200 rounded-xl px-3 py-2 text-xs text-jpc-700">
                Related record: <span className="font-semibold">{detail.related.label}</span> ({detail.related.type} #{detail.related.id})
              </div>
            ) : null}
          </div>
        </Modal>
      )}

      {/* ── View Recipients modal ── */}
      {recipientsLoading && !recipients && !detail && (
        <Modal open title="Notification Recipients" onClose={closeModals}>
          <LoadingPanel rows={2} />
        </Modal>
      )}
      {recipients && !detail && (
        <Modal
          open
          title={`Recipients — ${recipients.notification.title}`}
          onClose={closeModals}
          footer={
            <Button variant="secondary" onClick={closeModals}>
              Close
            </Button>
          }
        >
          <div className="space-y-4">
            {/* Recipient summary — delivered vs read are independent */}
            <div className="grid grid-cols-2 sm:grid-cols-4 gap-3">
              <StatCard label="Recipients" value={recipients.summary.total} />
              <StatCard label="Delivered" value={recipients.summary.delivered} tone="ok" />
              <StatCard label="Read" value={recipients.summary.read} tone="info" />
              <StatCard label="Unread" value={recipients.summary.unread} tone="warn" />
            </div>

            <div className="max-h-80 overflow-y-auto rounded-xl border border-slate-200 divide-y divide-slate-100">
              {recipients.recipients.map((r) => (
                <div key={r.notification_id} className="flex items-start justify-between gap-3 px-3 py-2">
                  <div className="min-w-0">
                    <p className="text-sm font-semibold text-slate-800">{r.name}</p>
                    <p className="text-[11px] text-slate-400">
                      {r.employee_number ? `#${r.employee_number} · ` : ''}
                      {r.department ?? 'No department'} · {r.email}
                    </p>
                  </div>
                  <div className="flex flex-col items-end gap-0.5">
                    <Badge tone={r.delivery_status === 'failed' ? 'danger' : 'ok'}>
                      {humanise(r.delivery_status)}
                    </Badge>
                    {r.is_read ? (
                      <p className="text-[11px] text-emerald-600">Read · {dateTime(r.read_at)}</p>
                    ) : (
                      <p className="text-[11px] text-amber-600">Unread</p>
                    )}
                  </div>
                </div>
              ))}
              {recipients.recipients.length === 0 && (
                <p className="text-sm text-slate-400 px-3 py-4 text-center">No recipients recorded.</p>
              )}
            </div>

            <p className="text-[11px] text-slate-400">
              Each recipient has an individual read state — only the recipient&apos;s own row changes when they read it.
            </p>
          </div>
        </Modal>
      )}
    </AdminPage>
  )
}
