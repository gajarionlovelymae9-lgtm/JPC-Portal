<?php

namespace App\Services\Reporting;

use App\Models\User;
use App\Services\Audit\ActivityLogger;
use Symfony\Component\HttpFoundation\Response;
use Symfony\Component\HttpFoundation\StreamedResponse;

class ReportExportService
{
    public function __construct(
        private readonly ActivityLogger $activityLogger
    ) {}

    public function exportCsv(string $reportType, array $reportData, User $user): StreamedResponse
    {
        $this->activityLogger->log(
            'REPORT_CSV_EXPORTED',
            "Exported {$reportType} report as CSV",
            $user
        );

        $filename = "{$reportType}-".date('Y-m-d').'.csv';

        $headers = [
            'Content-Type' => 'text/csv',
            'Content-Disposition' => "attachment; filename=\"{$filename}\"",
        ];

        return response()->stream(function () use ($reportType, $reportData) {
            $handle = fopen('php://output', 'w');

            // Header line
            fputcsv($handle, ['JPC Portal Official Report', strtoupper(str_replace('_', ' ', $reportType))]);
            fputcsv($handle, ['Generated Date', date('Y-m-d H:i:s')]);
            fputcsv($handle, []);

            if (isset($reportData['metrics'])) {
                fputcsv($handle, ['Metric', 'Value']);
                foreach ($reportData['metrics'] as $k => $v) {
                    fputcsv($handle, [ucwords(str_replace('_', ' ', $k)), is_array($v) ? json_encode($v) : $v]);
                }
            } elseif (isset($reportData['summary'])) {
                fputcsv($handle, ['Summary Item', 'Value']);
                foreach ($reportData['summary'] as $k => $v) {
                    fputcsv($handle, [ucwords(str_replace('_', ' ', $k)), is_array($v) ? json_encode($v) : $v]);
                }
            } elseif (isset($reportData['achievements'])) {
                fputcsv($handle, ['Rank', 'Employee', 'Department', 'Badge', 'Score']);
                foreach ($reportData['achievements'] as $a) {
                    fputcsv($handle, [$a['rank'], $a['employee_name'], $a['department'], $a['badge_type'], $a['score']]);
                }
            } elseif (isset($reportData['reports'])) {
                fputcsv($handle, ['Report Title', 'Employee', 'Department', 'Task', 'Submission Date']);
                foreach ($reportData['reports'] as $r) {
                    fputcsv($handle, [$r['title'], $r['employee'], $r['department'], $r['task'], $r['submitted_at']]);
                }
            }

            fclose($handle);
        }, 200, $headers);
    }

    public function exportExcel(string $reportType, array $reportData, User $user): StreamedResponse
    {
        $this->activityLogger->log(
            'REPORT_EXCEL_EXPORTED',
            "Exported {$reportType} report as Excel",
            $user
        );

        return $this->exportCsv($reportType, $reportData, $user);
    }

    public function exportPdf(string $reportType, array $reportData, User $user): Response
    {
        $this->activityLogger->log(
            'REPORT_PDF_EXPORTED',
            "Exported {$reportType} report as PDF",
            $user
        );

        $title = ucwords(str_replace('_', ' ', $reportType));
        $date = date('Y-m-d H:i:s');
        $period = $reportData['period'] ?? 'N/A';

        $html = "
        <!DOCTYPE html>
        <html>
        <head>
            <meta charset='utf-8'>
            <title>{$title}</title>
            <style>
                body { font-family: sans-serif; margin: 30px; color: #1e293b; }
                h1 { color: #312e81; font-size: 20px; margin-bottom: 5px; }
                .meta { font-size: 12px; color: #64748b; margin-bottom: 20px; border-bottom: 2px solid #e2e8f0; padding-bottom: 10px; }
                table { width: 100%; border-collapse: collapse; margin-top: 15px; font-size: 13px; }
                th { background-color: #f1f5f9; text-align: left; padding: 8px 12px; border: 1px solid #cbd5e1; }
                td { padding: 8px 12px; border: 1px solid #cbd5e1; }
                .footer { margin-top: 40px; font-size: 11px; color: #94a3b8; text-align: center; }
            </style>
        </head>
        <body>
            <h1>John Paul College — {$title}</h1>
            <div class='meta'>
                <strong>Reporting Period:</strong> {$period} |
                <strong>Generated On:</strong> {$date} |
                <strong>Generated By:</strong> {$user->name}
            </div>
            <table>
                <thead>
                    <tr><th>Parameter / Metric</th><th>Evaluated Value</th></tr>
                </thead>
                <tbody>";

        $items = $reportData['metrics'] ?? $reportData['summary'] ?? [];
        foreach ($items as $k => $v) {
            $label = ucwords(str_replace('_', ' ', $k));
            $val = is_array($v) ? json_encode($v) : $v;
            $html .= "<tr><td><strong>{$label}</strong></td><td>{$val}</td></tr>";
        }

        $html .= "
                </tbody>
            </table>
            <div class='footer'>
                JPC Portal • AI-Driven Employee Progress Monitoring Dashboard • Confidential Official Document
            </div>
        </body>
        </html>";

        return response($html, 200, [
            'Content-Type' => 'text/html',
            'Content-Disposition' => "inline; filename=\"{$reportType}.html\"",
        ]);
    }
}
