            self::TASK_WITH_INVALID_ASSIGNEE,
            self::TASK_WITHOUT_DEPARTMENT,
            self::INVALID_TASK_DATES,
            self::DUE_DATE_BEFORE_START_DATE,
            self::OVERDUE_TASK_WITH_INCONSISTENT_STATUS,
